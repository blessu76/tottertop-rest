def breadcrumb_html(items):
    return '<nav class="crumbs" aria-label="breadcrumb">%s</nav>' % " › ".join(
        '<a href="%s">%s</a>' % (esc(h), esc(l)) if h else "<span>%s</span>" % esc(l) for h, l in items)


def breadcrumb_ld(items):
    return {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": l, **({"item": url(h)} if h else {})} for i, (h, l) in enumerate(items)]}


def website_ld(lang):
    return {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": NAME, "inLanguage": lang, "publisher": {"@id": ORG_ID}}


def game_ld(lang, ctx):
    return {"@type": "VideoGame", "@id": SITE + "/#game", "name": NAME, "url": url(path_home(lang)),
            "description": ctx.t(lang, "home_desc"), "inLanguage": lang, "genre": [GAME["genre"]],
            "applicationCategory": "GameApplication", "gamePlatform": GAME["platforms"], "playMode": "SinglePlayer",
            "image": SITE + OG_IMAGE, "creator": ORG, "publisher": {"@id": ORG_ID}}


