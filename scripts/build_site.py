# ---------------------------------------------------------------- orchestration
def make_ctx(root, now=None, require_all=False):
    root = Path(root)
    now = now or dt.datetime.now(KST)
    i18n, errs = load_i18n(root)
    pages, e2 = load_pages(root)
    posts, e3 = load_journal(root)
    # date gate: a post dated after today (KST) is validated but written nowhere (no page, list, feed, sitemap or llms line)
    posts = [p for p in posts if p["published"][:10] <= now.strftime("%Y-%m-%d")]
    errs += e2 + e3
    langs = [l for l in LANGS if l in i18n and all((l, s) in pages for s in PAGE_SLUGS)]
    if not all(m in langs for m in MAIN_LANGS):
        errs.append("%s must be complete (i18n + %s)" % (" and ".join(MAIN_LANGS), " + ".join(PAGE_SLUGS)))
    for l in LANGS:
        if l not in langs and require_all:
            errs.append("language %s is incomplete (needs i18n/%s.json and pages/%s/{%s}.md)" % (l, l, l, ",".join(PAGE_SLUGS)))
    cname = root / "CNAME"
    if cname.is_file() and cname.read_text(encoding="utf-8").strip() != DOMAIN:
        errs.append("CNAME (%s) does not match games.json domain (%s)" % (cname.read_text(encoding="utf-8").strip(), DOMAIN))
    return Ctx(root, i18n, pages, langs, now, posts), errs


def build_all(ctx):
    """-> {relative file path: text}"""
    files = {}

    def put(path, text):
        files[path.lstrip("/") + "index.html" if path.endswith("/") else path.lstrip("/")] = text

    for l in ctx.langs:
        put(*build_home(ctx, l))
        for slug in PAGE_SLUGS:
            put(*build_page(ctx, l, slug))
    for l in ctx.journal_langs:  # no /ja/journal/: the journal is written in en + ko only
        put(*build_journal_list(ctx, l))
        files[path_feed(l).lstrip("/")] = build_feed(ctx, l)
        for p in ctx.posts_in(l):
            put(*build_post(ctx, l, p))
    files["404.html"] = build_404(ctx)
    files["sitemap.xml"] = build_sitemap(ctx)
    files["robots.txt"] = build_robots()
    files["llms.txt"] = build_llms(ctx)
    return files


def clean(root):
    root = Path(root)
    for name in list(PAGE_SLUGS) + list(HIDDEN_PAGES) + [JOURNAL_DIR] + [l for l in LANGS if l != "en"]:
        d = root / name
        if d.is_dir():
            shutil.rmtree(d)
    for name in ("index.html", "404.html", "sitemap.xml", "robots.txt", "llms.txt"):
        f = root / name
        if f.is_file():
            f.unlink()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="validate sources only")
    ap.add_argument("--require-all", action="store_true", help="fail unless every language in games.json is complete")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    ctx, errs = make_ctx(root, require_all=a.require_all)
    if errs:
        print("build_site: %d problem(s)\n  %s" % (len(errs), "\n  ".join(errs)), file=sys.stderr)
        return 1
    files = build_all(ctx)
    if a.check:
        print("build_site: sources OK — %d language(s), %d file(s) would be written" % (len(ctx.langs), len(files)))
        return 0
    clean(root)
    for rel, text in files.items():
        f = root / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
    print("build_site: wrote %d file(s) — %d language(s)" % (len(files), len(ctx.langs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
